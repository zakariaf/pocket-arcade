#!/usr/bin/env node
// check-app-art.mjs: proves each app's generated icon and splash PNGs meet Apple's rules and the
// Toybox layout: 1024 x 1024, light opaque and full bleed, dark with a transparent background,
// tinted grayscale and opaque, splash logos on transparency, and every glyph inside its safe area.
// From Android step 2 (android-config.ts exists) also the Android outputs: the adaptive icon's
// foreground and monochrome layers inside the 66 dp circle, the Android 12 splash icons inside
// their masking circle, the 512 px Play icon, and their wiring.
// Run: node ${CLAUDE_SKILL_DIR}/scripts/check-app-art.mjs [repo-root] [--app <game-id>]

import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

import { createReporter, fail, maskComments, parseArgs, requireDir, run } from './check-lib.mjs';
import { readPng } from './lib/png.mjs';

const SPEC = {
  name: 'check-app-art',
  summary: 'Checks apps/<game>/assets/generated: the app icon (light, dark, tinted), splash logos and, from Android step 2, the Android adaptive icon, splash icons and Play icon written by render-art.ts, and that the Expo config uses them.',
  usage: '[options] [repo-root]',
  options: {
    app: { type: 'string', multiple: true, value: 'game-id', help: 'Check only this app (default: every Expo app in apps/)' },
    json: { type: 'boolean', help: 'Also print the problems as one JSON line' },
  },
  positionals: { min: 0, max: 1 },
  details: [
    'Rules:',
    '  art-missing        a generated PNG is missing (the Android ones are due at Android step 2, once',
    '                     packages/shell/src/config/android-config.ts exists; before that a SKIP line)',
    '  art-format         not a readable 8-bit PNG, or not 1024 x 1024 (play-icon-512.png: 512 x 512)',
    '  art-light-opaque   icon-light.png has transparent pixels (Expo would flatten them onto white)',
    '  art-dark-clear     icon-dark.png has no transparent background',
    '  art-tinted-gray    icon-tinted.png is not grayscale, or not opaque',
    '  art-splash-clear   a splash logo has no transparent background',
    '  art-safe-area      the glyph leaves the central 62 % (icons) or touches the edge (splash); on Android',
    '                     a layer leaves the 66 dp circle of 108 dp, or a splash icon the 192 dp circle of 288 dp',
    '  art-adaptive-clear an adaptive icon layer has no transparent background (the launcher paints the accent)',
    '  art-monochrome     android-icon-monochrome.png is not one white colour on alpha (the launcher tints it)',
    '  art-unwired        withShell does not end in withGameArt(), splash-grounds.ts lacks the game, or expo-splash-screen is not a dependency;',
    '                     from Android step 2 also: no android.adaptiveIcon, no Android splash icon, or no accent for the game',
    '  generated-header   splash-grounds.ts lacks "// GENERATED by packages/tooling/src/art/render-art.ts" in its first 3',
    '                     lines (hand-edited, or the header dropped; the test-edit check exempts generated files by that line)',
    '',
    'Regenerate with: node packages/tooling/src/art/render-art.ts --app <game-id>',
  ].join('\n'),
};

const SIZE = 1024;
const FILES = ['icon-light.png', 'icon-dark.png', 'icon-tinted.png', 'splash-logo.png', 'splash-logo-dark.png'];
const ANDROID_FILES = ['android-icon-foreground.png', 'android-icon-monochrome.png', 'android-splash-icon.png', 'android-splash-icon-dark.png', 'play-icon-512.png'];
const SIZES = { 'play-icon-512.png': 512 };
/** Android step 2 copies this file (architecture-and-boundaries); from then on the Android art is due. */
const ANDROID_DUE = 'packages/shell/src/config/android-config.ts';
const ANDROID_DUE_REASON = `due at Android step 2: ${ANDROID_DUE} not yet created`;
/** Adaptive icon: the 66 dp safe circle of the 108 dp canvas; Android 12 splash: 192 dp of 288 dp. */
const ADAPTIVE_CIRCLE = 66 / 108;
const SPLASH_CIRCLE = 192 / 288;
/** Pixels of anti-aliasing allowed outside a circle. */
const CIRCLE_SLACK = 2;
/** Glyph area: the central 62 % plus 1 % for anti-aliasing and the die-cut ring's edge. */
const SAFE = 0.64;
/** Colour distance (0-255 max channel) that counts as "not background". */
const INK_DELTA = 24;
const REGENERATE = (id) => `Run: node packages/tooling/src/art/render-art.ts --app ${id}, look at the PNGs, commit them.`;

function expoApps(root) {
  const appsDir = join(root, 'apps');
  if (!existsSync(appsDir)) return [];
  return readdirSync(appsDir).filter((id) => existsSync(join(appsDir, id, 'app.config.ts')) || existsSync(join(appsDir, id, 'app.json'))).sort();
}

function pixel(img, x, y) {
  const at = (y * img.width + x) * 4;
  return [img.rgba[at], img.rgba[at + 1], img.rgba[at + 2], img.rgba[at + 3]];
}

/** Bounding box of the pixels that differ from the background (by colour or by alpha). */
function contentBox(img, isContent) {
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (let y = 0; y < img.height; y += 1) {
    for (let x = 0; x < img.width; x += 1) {
      if (!isContent(pixel(img, x, y))) continue;
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
  }
  return Number.isFinite(minX) ? { minX, minY, maxX, maxY } : null;
}

function differsFrom(background) {
  return (p) => Math.max(Math.abs(p[0] - background[0]), Math.abs(p[1] - background[1]), Math.abs(p[2] - background[2])) > INK_DELTA;
}

function checkSafeArea(report, { file, img, isContent, safe, id }) {
  const box = contentBox(img, isContent);
  if (box === null) {
    report.problem({ file, rule: 'art-safe-area', message: 'the image is empty (no glyph)', fix: REGENERATE(id) });
    return;
  }
  const lo = Math.floor((img.width * (1 - safe)) / 2);
  const hi = Math.ceil(img.width - lo);
  if (box.minX < lo || box.minY < lo || box.maxX >= hi || box.maxY >= hi) {
    report.problem({ file, rule: 'art-safe-area', message: `glyph spans ${box.minX},${box.minY} to ${box.maxX},${box.maxY}; the safe area is ${lo}..${hi - 1}`, fix: `Keep the glyph inside the central ${Math.round(safe * 100)} % (render-art.ts GLYPH), then regenerate.` });
  }
}

/** Every visible pixel inside the central circle of `diameter` (a fraction of the width). */
function checkCircle(report, { file, img, diameter, id, what }) {
  const center = img.width / 2;
  const limit = (img.width * diameter) / 2 + CIRCLE_SLACK;
  let worst = 0;
  for (let y = 0; y < img.height; y += 1) {
    for (let x = 0; x < img.width; x += 1) {
      if (pixel(img, x, y)[3] === 0) continue;
      const distance = Math.hypot(x + 0.5 - center, y + 0.5 - center);
      if (distance > worst) worst = distance;
    }
  }
  if (worst === 0) {
    report.problem({ file, rule: 'art-safe-area', message: 'the image is empty (no glyph)', fix: REGENERATE(id) });
  } else if (worst > limit) {
    report.problem({ file, rule: 'art-safe-area', message: `the glyph reaches ${Math.round(worst)} px from the centre; ${what} allows ${Math.round(limit)} px`, fix: `Keep it inside ${what} (render-art.ts uses art-outputs.ts), then regenerate.` });
  }
}

function isWhiteOnAlpha(img) {
  for (let i = 0; i < img.rgba.length; i += 4) {
    if (img.rgba[i + 3] === 0) continue;
    if (img.rgba[i] < 250 || img.rgba[i + 1] < 250 || img.rgba[i + 2] < 250) return false;
  }
  return true;
}

function isOpaque(img) {
  for (let i = 3; i < img.rgba.length; i += 4) if (img.rgba[i] !== 255) return false;
  return true;
}

function isGray(img) {
  for (let i = 0; i < img.rgba.length; i += 4) {
    const [r, g, b] = [img.rgba[i], img.rgba[i + 1], img.rgba[i + 2]];
    if (Math.abs(r - g) > 1 || Math.abs(g - b) > 1) return false;
  }
  return true;
}

function cornersClear(img) {
  const last = img.width - 1;
  return [[0, 0], [last, 0], [0, last], [last, last]].every(([x, y]) => pixel(img, x, y)[3] === 0);
}

function checkOne(report, id, name, img) {
  const file = `apps/${id}/assets/generated/${name}`;
  if (name === 'icon-light.png') {
    if (!isOpaque(img)) report.problem({ file, rule: 'art-light-opaque', message: 'the light icon has transparent pixels', fix: 'Draw a full-bleed background (the accent) first; iOS masks the corners itself.' });
    checkSafeArea(report, { file, img, isContent: differsFrom(pixel(img, 0, 0)), safe: SAFE, id });
  } else if (name === 'icon-dark.png') {
    if (!cornersClear(img)) report.problem({ file, rule: 'art-dark-clear', message: 'the dark icon has no transparent background', fix: 'Leave the background transparent; iOS draws the dark backdrop.' });
    checkSafeArea(report, { file, img, isContent: (p) => p[3] > 0, safe: SAFE, id });
  } else if (name === 'icon-tinted.png') {
    if (!isGray(img) || !isOpaque(img)) report.problem({ file, rule: 'art-tinted-gray', message: 'the tinted icon must be opaque grayscale', fix: 'Render it through the luma colour filter over the dark ground (render-art.ts GRAYSCALE).' });
    checkSafeArea(report, { file, img, isContent: differsFrom(pixel(img, 0, 0)), safe: SAFE, id });
  } else if (name === 'play-icon-512.png') {
    if (!isOpaque(img)) report.problem({ file, rule: 'art-light-opaque', message: 'the Play icon has transparent pixels', fix: 'Draw it as the light icon: the accent full bleed, the glyph at 62 %.' });
    checkSafeArea(report, { file, img, isContent: differsFrom(pixel(img, 0, 0)), safe: SAFE, id });
  } else if (name === 'android-icon-foreground.png' || name === 'android-icon-monochrome.png') {
    if (!cornersClear(img)) report.problem({ file, rule: 'art-adaptive-clear', message: 'the adaptive icon layer has no transparent background', fix: 'Draw only the glyph; android.adaptiveIcon.backgroundColor (the accent) is the background.' });
    if (name === 'android-icon-monochrome.png' && !isWhiteOnAlpha(img)) report.problem({ file, rule: 'art-monochrome', message: 'the themed icon layer is not one white colour on alpha', fix: 'Render it through render-art.ts MONOCHROME (white, alpha = the logo alpha minus its luma).' });
    checkCircle(report, { file, img, diameter: ADAPTIVE_CIRCLE, id, what: 'the 66 dp safe circle of the 108 dp adaptive icon' });
  } else if (name.startsWith('android-splash-icon')) {
    if (!cornersClear(img)) report.problem({ file, rule: 'art-splash-clear', message: 'the Android splash icon has no transparent background', fix: 'The splash plugin paints the ground; the icon PNG must be transparent around the tile.' });
    checkCircle(report, { file, img, diameter: SPLASH_CIRCLE, id, what: 'the 192 dp circle of the 288 dp Android 12 splash icon' });
  } else {
    if (!cornersClear(img)) report.problem({ file, rule: 'art-splash-clear', message: 'the splash logo has no transparent background', fix: 'The splash plugin paints the ground; the logo PNG must be transparent around the tile.' });
    checkSafeArea(report, { file, img, isContent: (p) => p[3] > 0, safe: 0.99, id });
  }
}

const CONFIG_DIR = 'packages/shell/src/config';
const GROUNDS_FILE = `${CONFIG_DIR}/splash-grounds.ts`;
/** render-art.ts writes this on line 2 of every file it generates; check-test-edits exempts such files. */
const GENERATED_LINE = '// GENERATED by packages/tooling/src/art/render-art.ts';

/** From Android step 2: the composer adds the adaptive icon and the Android splash icon, and the grounds hold the accent. */
function checkAndroidWiring(report, { composerText, grounds, id }) {
  const artConfig = `${CONFIG_DIR}/art-config.ts`;
  if (!/\badaptiveIcon\b/.test(composerText)) report.problem({ file: artConfig, rule: 'art-unwired', message: 'withShell does not add the Android adaptive icon', fix: 'withArt sets android.adaptiveIcon { foregroundImage, monochromeImage, backgroundColor: accent } (references/app-icon-and-splash.md).' });
  if (!composerText.includes('android-splash-icon.png')) report.problem({ file: artConfig, rule: 'art-unwired', message: 'withShell does not add the Android 12 splash icon', fix: "splashPlugin passes android: { image: './assets/generated/android-splash-icon.png', imageWidth: 288, dark: { image: ...-dark.png } }." });
  const escaped = id.replace(/[-]/g, '\\-');
  if (!new RegExp(`(['"]?)${escaped}\\1\\s*:\\s*\\{[^}]*\\baccent:\\s*'#[0-9A-Fa-f]{6}'`).test(grounds)) {
    report.problem({ file: GROUNDS_FILE, rule: 'art-unwired', message: `no accent colour for ${id} (the adaptive icon background)`, fix: REGENERATE(id) });
  }
}

/** withShell must end in withGameArt(), the game needs its splash grounds, and the app the splash plugin. */
function checkWiring(report, root, id, isAndroidDue) {
  const isExpoApp = ['app.config.ts', 'app.json'].some((name) => existsSync(join(root, 'apps', id, name)));
  if (!isExpoApp) return;
  const configDir = join(root, CONFIG_DIR);
  const composers = existsSync(configDir)
    ? readdirSync(configDir).filter((name) => name.endsWith('.ts') && !name.endsWith('.test.ts'))
    : [];
  const texts = composers.map((name) => maskComments(readFileSync(join(configDir, name), 'utf8')));
  const callsArt = texts.some((text) => /\bwithGameArt\s*\(/.test(text.replace(/function\s+withGameArt\s*\(/g, '')));
  if (!callsArt) {
    report.problem({ file: `${CONFIG_DIR}/with-shell.ts`, rule: 'art-unwired', message: 'withShell does not add the generated icon and splash', fix: 'End withShell with return withGameArt({ ...the composed config }, game.id) (references/app-icon-and-splash.md); never edit app.config.ts.' });
  }
  const grounds = existsSync(join(root, GROUNDS_FILE)) ? readFileSync(join(root, GROUNDS_FILE), 'utf8') : '';
  if (grounds !== '' && !grounds.split('\n').slice(0, 3).some((line) => line.startsWith(GENERATED_LINE))) {
    report.problem({ file: GROUNDS_FILE, rule: 'generated-header', message: `splash-grounds.ts lacks "${GENERATED_LINE}" in its first 3 lines`, fix: `${REGENERATE(id)} The file is written only by render-art.ts; never edit it by hand.` });
  }
  const escaped = id.replace(/[-]/g, '\\-');
  if (!new RegExp(`(['"]?)${escaped}\\1\\s*:\\s*\\{\\s*light:\\s*'#[0-9A-Fa-f]{6}'`).test(grounds)) {
    report.problem({ file: GROUNDS_FILE, rule: 'art-unwired', message: `no splash grounds for ${id}`, fix: REGENERATE(id) });
  }
  const pkgFile = `apps/${id}/package.json`;
  let pkg = {};
  try {
    pkg = JSON.parse(readFileSync(join(root, pkgFile), 'utf8'));
  } catch {
    // A missing or unreadable package.json is reported below as a missing dependency.
  }
  if (!pkg.dependencies?.['expo-splash-screen']) {
    report.problem({ file: pkgFile, rule: 'art-unwired', message: 'expo-splash-screen is not a dependency of the app', fix: `Run: cd apps/${id} && npx expo install expo-splash-screen` });
  }
  if (isAndroidDue) checkAndroidWiring(report, { composerText: texts.join('\n'), grounds, id });
  else report.skip({ file: `${CONFIG_DIR}/art-config.ts`, rule: 'art-unwired', message: ANDROID_DUE_REASON });
}

run(async () => {
  const { options, positionals } = parseArgs(process.argv.slice(2), SPEC);
  const root = requireDir(positionals[0] ?? '.', 'app repo root');
  const apps = options.app.length > 0 ? options.app : expoApps(root);
  if (apps.length === 0) fail(`nothing to check: no Expo app (apps/<id>/app.config.ts) under ${root}`, 'Run from the app repo root, or pass --app <game-id>.');
  const report = createReporter({ name: 'check-app-art', json: options.json });
  const isAndroidDue = existsSync(join(root, ANDROID_DUE));
  let checked = 0;
  for (const id of apps) {
    checkWiring(report, root, id, isAndroidDue);
    for (const name of [...FILES, ...ANDROID_FILES]) {
      const file = `apps/${id}/assets/generated/${name}`;
      const isAndroid = ANDROID_FILES.includes(name);
      if (isAndroid && !isAndroidDue) {
        report.skip({ file, rule: 'art-missing', message: ANDROID_DUE_REASON });
        continue;
      }
      checked += 1;
      if (!existsSync(join(root, file))) {
        report.problem({ file, rule: 'art-missing', message: 'generated art is missing', fix: REGENERATE(id) });
        continue;
      }
      let img;
      try {
        img = readPng(readFileSync(join(root, file)));
      } catch (error) {
        report.problem({ file, rule: 'art-format', message: error.message, fix: REGENERATE(id) });
        continue;
      }
      const size = SIZES[name] ?? SIZE;
      if (img.width !== size || img.height !== size) {
        report.problem({ file, rule: 'art-format', message: `${img.width} x ${img.height}, must be ${size} x ${size}`, fix: REGENERATE(id) });
        continue;
      }
      checkOne(report, id, name, img);
    }
  }
  return report.finish({ checked, unit: 'images' });
});
